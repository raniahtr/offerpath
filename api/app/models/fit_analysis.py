import datetime as dt
from enum import StrEnum

from sqlalchemy import CheckConstraint, DateTime, ForeignKey, Index, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db import Base


class AnalysisSource(StrEnum):
    API = "api"  # generated by the app's LLM
    MANUAL = "manual"  # the user ran the prompt in their own chat and pasted the answer


_SOURCE_VALUES = ", ".join(f"'{s.value}'" for s in AnalysisSource)


class FitAnalysis(Base):
    __tablename__ = "fit_analyses"
    __table_args__ = (
        CheckConstraint("score BETWEEN 0 AND 100", name="score_range"),
        CheckConstraint(f"source IN ({_SOURCE_VALUES})", name="source_valid"),
        # Cache lookup: same user + same inputs (CV, posting, prompt, model) -> reuse.
        Index("ix_fit_analyses_user_id_input_hash", "user_id", "input_hash"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    user_id: Mapped[str] = mapped_column(String(255))
    # Deleting a posting deletes its analyses (in the database, not only in Python).
    posting_id: Mapped[int] = mapped_column(
        ForeignKey("postings.id", ondelete="CASCADE"), index=True
    )
    score: Mapped[int] = mapped_column(Integer)
    matched_skills: Mapped[list[str]] = mapped_column(JSONB)
    missing_skills: Mapped[list[str]] = mapped_column(JSONB)
    explanation: Mapped[str] = mapped_column(Text)
    source: Mapped[str] = mapped_column(String(10))
    model: Mapped[str | None] = mapped_column(String(100))
    input_hash: Mapped[str] = mapped_column(String(64))
    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
